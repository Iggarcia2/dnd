'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const storage=new Map();
const ctx=vm.createContext({console,localStorage:{setItem:(k,v)=>storage.set(k,v),getItem:k=>storage.get(k)||null},Intl,Date,Number,Math,Object,Array,Set,structuredClone});
for(const filename of ['config.js','estimacion.js','interfaz.js']) vm.runInContext(fs.readFileSync(path.join(root,'js',filename),'utf8'),ctx,{filename});
const data=JSON.parse(fs.readFileSync(path.join(root,'data/biblioteca_ratios.json'),'utf8'));
const published=JSON.parse(fs.readFileSync(path.join(root,'data/calibracion.json'),'utf8'));
vm.runInContext(`LIB=${JSON.stringify(data)};RATIOS=LIB.ratios;BY_ID=Object.fromEntries(RATIOS.map(r=>[r.id,r]));CALIBRATION=mergeCalibration(${JSON.stringify(published)});PUBLISHED_CALIBRATION=structuredClone(CALIBRATION);state=initialState();`,ctx);
const ev=s=>vm.runInContext(s,ctx);
const baseline=ev('calculate()');
assert.ok(baseline.total>100);
assert.ok(Math.abs(baseline.budget-baseline.total*35)<1e-7,'Tarifa única conserva presupuesto previo');
ev("state.tariffMode='disciplina';state.disciplineRates={CIV:20,EST:40,MEC:50,PIP:45,ELE:55,INS:47,GES:25};");
const result=ev('calculate()');
assert.equal(result.total,baseline.total,'Las tarifas no cambian las horas');
const expected=ev('DISC.reduce((acc,d)=>acc+calculate().byDisc[d.id]*tariffForDisc(d.id),0)');
assert.ok(Math.abs(result.budget-expected)<1e-7,'Costo por disciplina exacto');
assert.ok(Math.abs(result.budget-baseline.budget)>1,'Los precios diferentes afectan la cotización');
const originalCost=result.budget;
ev('state.disciplineRates.CIV=75');
const updated=ev('calculate()');
assert.ok(Math.abs(updated.budget-originalCost-55*updated.byDisc.CIV)<1e-7,'Solo cambia el costo civil');
const raw=ev('JSON.stringify(state)');
const obj=JSON.parse(raw);
ev(`state=mergeState(initialState(),${JSON.stringify(obj)});`);
assert.equal(ev('state.tariffMode'),'disciplina');
assert.equal(ev('state.disciplineRates.CIV'),75);
ev('CALIBRATION.disciplineRates={CIV:80,INS:47};persistCalibration();');
const cal=JSON.parse(storage.get('estimador_ingenieria_calibracion_v1'));
assert.equal(cal.disciplineRates.CIV,80);
assert.equal(ev('mergeCalibration(JSON.parse(localStorage.getItem(CALIBRATION_KEY))).disciplineRates.INS'),47);
ev('state.disciplineRates={};');
assert.equal(ev('tariffForDisc("CIV")'),80,'Prioridad de valor base');
assert.equal(ev('tariffForDisc("ELE")'),35,'Fallback de tarifa común');
ev("state.tariffMode='unica';");
assert.equal(ev('calculate().budget'),ev('calculate().total*state.rate'),'Volver a tarifa única');
console.log('✓ V5.2: tarifa única, diferenciada, subtotal por disciplina, persistencia, prioridades y compatibilidad');
